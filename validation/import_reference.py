"""Import original MASS-GT trips for controlled assignment comparisons.
An imported trip is evidence, not a NetSy-synthesized tour.
"""
import argparse
from pathlib import Path
import geopandas as gpd
import numpy as np
import pandas as pd
p=argparse.ArgumentParser();p.add_argument('label',choices=['REF','UCC']);p.add_argument('output',type=Path);a=p.parse_args();a.output.mkdir(parents=True,exist_ok=True)
ref=Path('/workdir/sweden/mass-gt/runs/NL_'+a.label)
vehicles=['truck_small','truck_medium','truck_large','truck_trailer_small','truck_trailer_large','tractor_trailer','special_vehicle','van','levv','moped']
segments=['food','miscellaneous','temperature_controlled','facility','construction','waste','parcel_consolidated','dangerous']
combustions=['fuel','electric','hydrogen','hybrid','biofuel']
capacities=pd.read_csv('/workdir/sweden/mass-gt/data/NL_main/parameters/CarryingCapacity.txt',sep='\t').set_index('vehicle_type').capacity_kg
for kind,file in [('freight','Tours'),('parcels','ParcelSchedule')]:
 t=pd.read_csv(ref/f'{file}_{a.label}.csv')
 if kind=='freight':
  rows=pd.DataFrame({'departure':t.TRIP_DEPTIME,'vehicle':t.VEHTYPE.map(dict(enumerate(vehicles))), 'segment':t.LS.map(dict(enumerate(segments))), 'origin_zone_id':t.ORIG,'destination_zone_id':t.DEST,'utilization':t.TRIP_WEIGHT*1000/t.VEHTYPE.map(capacities)})
  if a.label=='UCC':rows['combustion']=t.COMBTYPE.map(dict(enumerate(combustions)))
 else:
  rows=pd.DataFrame({'departure':t.TripDepTime,'vehicle':t.VehType.map({'Van':'van','LEVV':'levv'}),'segment':'parcel_deliveries','origin_zone_id':t.O_zone,'destination_zone_id':t.D_zone,'utilization':.5})
  if rows.vehicle.isna().any(): raise ValueError(f'unknown parcel vehicles {t.VehType.unique()}')
  if a.label=='UCC':
   zones=gpd.read_file('/workdir/netherlands-ucc/zones.gpkg',ignore_geometry=True).set_index('zone_id').policy_zone
   rows['combustion']=np.where(t.OrigType=='UCC','electric',np.where(t.D_zone.map(zones)>0,'hybrid','fuel'))
 name='tours.gpkg' if kind=='freight' else 'delivery_tours.gpkg'
 target=a.output/name
 if target.is_symlink():target.unlink()
 gpd.GeoDataFrame(rows,geometry=gpd.points_from_xy(np.zeros(len(rows)),np.zeros(len(rows))),crs=28992).to_file(target,driver='GPKG')

# Original matrices are imported as original evidence, not regenerated by NetSy.
from netsy.helpers.skims import write_matrices
original_zones=gpd.read_file('/workdir/sweden/mass-gt/data/NL_main/data/Zones_v6.shp',ignore_geometry=True)
matrices={}
for name,file in [('service','TripsVanService.mtx'),('construction','TripsVanConstruction.mtx')]:
 raw=np.fromfile(ref/file,dtype=np.float32)[1:]
 count=int(round(np.sqrt(len(raw))))
 if count*count != len(raw): raise ValueError(f'{file}: matrix is not square')
 matrices[name]=raw.reshape(count,count)
order=sorted(original_zones.AREANR.astype(int))+list(range(99999901,99999901+count-len(original_zones)))
path=a.output/'trip_matrices.omx'
if path.is_symlink():path.unlink()
write_matrices(str(path),[str(z) for z in order],matrices)
